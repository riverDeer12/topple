// Pre-generates the endless sequence and the daily puzzles into web/puzzles.js,
// so the game never has to run the (slow) generator on a phone. The game and the
// API server read the same file; past the end of the file both fall back to
// web/gen.js, which produces exactly the same boards.
// Run: node tools/generate-puzzles.js [endlessCount=300] [firstDay=2026-11-01] [days=366]
// Uses all CPU cores. Results are cached in tools/.cache/, so it can be stopped and resumed.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { Worker, isMainThread, parentPort } = require('worker_threads');
const G = require('../web/gen.js');

if (!isMainThread) {
  parentPort.on('message', t => {
    const r = t.kind === 'endless' ? G.endlessPuzzle(t.n) : G.dailyPuzzle(t.date);
    parentPort.postMessage({ ...t, level: r.level });
  });
  return;
}

const [endlessCount = 300, firstDay = G.today(), days = 366] = process.argv.slice(2);
const CACHE = path.join(__dirname, '.cache');
fs.mkdirSync(CACHE, { recursive: true });
const specKey = s => require('crypto').createHash('sha1').update(JSON.stringify(s) + JSON.stringify(G.GAME)).digest('hex').slice(0, 10);
const cacheFile = t => path.join(CACHE, t.kind === 'endless'
  ? `endless-${t.n}-${specKey(G.endlessSpec(t.n))}.json` : `daily-${t.date}-${specKey(G.dailySpec(t.date))}.json`);

const tasks = [];
for (let n = 1; n <= +endlessCount; n++) tasks.push({ kind: 'endless', n });
const d0 = new Date(firstDay + 'T12:00:00Z');
for (let i = 0; i < +days; i++) tasks.push({ kind: 'daily', date: new Date(d0.getTime() + i * 864e5).toISOString().slice(0, 10) });

const results = new Map();
const todo = [];
for (const t of tasks) {
  const f = cacheFile(t);
  if (fs.existsSync(f)) results.set(f, JSON.parse(fs.readFileSync(f, 'utf8')));
  else todo.push(t);
}
console.log(`${tasks.length} zagonetki, ${tasks.length - todo.length} iz cachea, ${todo.length} za generiranje.`);

let done = 0;
const t0 = Date.now();
function finish() {
  const endless = [], daily = {};
  for (const t of tasks) {
    const r = results.get(cacheFile(t));
    if (!r || !r.level) { console.error('Nedostaje zagonetka', t); process.exit(1); }
    if (t.kind === 'endless') endless.push(r.level); else daily[t.date] = r.level;
  }
  const lines = o => Object.entries(o).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n');
  fs.writeFileSync(path.join(__dirname, '../web/puzzles.js'),
    '// Generated by tools/generate-puzzles.js from web/gen.js. Same format as levels.js.\n' +
    '// endless[n - 1] is endless puzzle n; daily is keyed by date (Europe/Zagreb).\n' +
    'const PUZZLES = {\nendless: [\n' + endless.map(l => '  ' + JSON.stringify(l)).join(',\n') +
    '\n],\ndaily: {\n' + lines(daily) + '\n}\n};\nif (typeof module !== "undefined") module.exports = PUZZLES;\n');
  console.log(`Zapisano u web/puzzles.js: ${endless.length} beskonačnih, ${Object.keys(daily).length} dnevnih.`);
  process.exit(0);
}
if (!todo.length) finish();
const workers = Math.max(1, os.cpus().length);
let next = 0, active = 0;
for (let w = 0; w < Math.min(workers, todo.length); w++) {
  const worker = new Worker(__filename);
  const feed = () => { if (next < todo.length) { active++; worker.postMessage(todo[next++]); } else worker.terminate(); };
  worker.on('message', r => {
    active--;
    const f = cacheFile(r);
    const entry = { level: r.level };
    fs.writeFileSync(f, JSON.stringify(entry));
    results.set(f, entry);
    done++;
    if (done % 10 === 0 || done === todo.length) console.log(`${done}/${todo.length} (${Math.round((Date.now() - t0) / 1000)} s)`);
    if (done === todo.length) finish();
    feed();
  });
  feed();
}
